import {
  Injectable,
  BadRequestException,
  NotFoundException,
} from '@nestjs/common';
import { PrismaService } from '../../database/prisma.service';
import { InvoiceStatus, PaymentMethod } from '@calyvia/shared';
import { CommunicationService } from '../communication/communication.service';
import { InvoicePdfService } from './invoice-pdf.service';
import { MpesaService } from './mpesa.service';
import { TriggerMpesaStkDto } from './dto/trigger-mpesa-stk.dto';

export interface CreateInvoiceDto {
  patientId?: string;
  admissionId?: string;
  items: Array<{ description: string; quantity: number; unitPriceKES: number }>;
  dueDate?: string;
  /** Used when there is no patient record yet (walk-in / manual invoice). */
  billToName?: string;
  billToPhone?: string;
  /** Separate WhatsApp delivery number, encoded in notes so no DB migration is needed. */
  whatsappNumber?: string;
  notes?: string;
  discount?: number;
  /** Set by the automatic generator; encoded in notes so no DB migration is required. */
  autoGenerated?: boolean;
}

export interface RecordPaymentDto {
  invoiceId: string;
  amountKES: number;
  paymentMethod: PaymentMethod;
  transactionRef?: string;
  receivedBy: string;
}

const PROGRAM_RATES: Record<string, { label: string; amount: number; inpatient: boolean }> = {
  DETOX_ONLY: { label: 'Medical detox program', amount: 45000, inpatient: true },
  REHAB_30_DAYS: { label: '30-day residential rehabilitation', amount: 120000, inpatient: true },
  REHAB_60_DAYS: { label: '60-day residential rehabilitation', amount: 210000, inpatient: true },
  REHAB_90_DAYS: { label: '90-day residential rehabilitation', amount: 285000, inpatient: true },
  OUTPATIENT: { label: 'Outpatient treatment program', amount: 25000, inpatient: false },
  AFTERCARE_ONLY: { label: 'Aftercare program', amount: 18000, inpatient: false },
};

const BED_RATE_KES = 15000;

@Injectable()
export class BillingService {
  constructor(
    private prisma: PrismaService,
    private communication: CommunicationService,
    private pdf: InvoicePdfService,
    private mpesa: MpesaService,
  ) {}

  private generateInvoiceNumber(): string {
    const rand = Math.floor(1000 + Math.random() * 9000);
    return `INV-${new Date().getFullYear()}-${rand}`;
  }

  private generateReceiptNumber(): string {
    const rand = Math.floor(1000 + Math.random() * 9000);
    return `REC-${new Date().getFullYear()}-${rand}`;
  }

  private buildNotes(dto: CreateInvoiceDto): string {
    const parts: string[] = [];
    if (dto.billToName?.trim()) parts.push(`Bill to: ${dto.billToName.trim()}`);
    if (dto.billToPhone?.trim()) parts.push(`Phone: ${dto.billToPhone.trim()}`);
    if (dto.whatsappNumber?.trim()) parts.push(`WhatsApp: ${dto.whatsappNumber.trim()}`);
    parts.push(`Source: ${dto.autoGenerated ? 'AUTO' : 'MANUAL'}`);
    if (dto.notes?.trim()) parts.push(dto.notes.trim());
    return parts.join(' | ');
  }

  private noteValue(notes: any, label: string): string | null {
    const match = String(notes ?? '').match(new RegExp(`${label}:\\s*([^|]+)`, 'i'));
    return match?.[1]?.trim() || null;
  }

  private patientName(patient: any): string {
    const names = [patient?.firstName, patient?.lastName].filter(Boolean);
    return names.join(' ').trim();
  }

  private invoiceNumber(invoice: any): string {
    return String(invoice?.invoiceNumber ?? invoice?.invoice_number ?? 'DRAFT');
  }

  private invoiceValue(invoice: any, ...keys: string[]): any {
    for (const key of keys) {
      const value = invoice?.[key];
      if (value !== undefined && value !== null && value !== '') return value;
    }
    return null;
  }

  async createInvoice(dto: CreateInvoiceDto) {
    if (!dto.items || dto.items.length === 0) {
      throw new BadRequestException('An invoice must contain at least one line item.');
    }

    const invNumber = this.generateInvoiceNumber();
    const subtotal = dto.items.reduce(
      (sum, item) => sum + (Number(item.quantity) || 1) * (Number(item.unitPriceKES) || 0),
      0,
    );
    const discount = Math.max(0, Number(dto.discount) || 0);
    const totalAmount = Math.max(0, subtotal - discount);

    try {
      if (this.prisma && this.prisma.invoice) {
        const inv = await this.prisma.invoice.create({
          data: {
            invoiceNumber: invNumber,
            patientId: dto.patientId || null,
            admissionId: dto.admissionId || null,
            issueDate: new Date(),
            dueDate: dto.dueDate ? new Date(dto.dueDate) : new Date(Date.now() + 86400000 * 7),
            status: InvoiceStatus.ISSUED as any,
            subtotal,
            discount,
            totalAmountKES: totalAmount,
            paidAmountKES: 0,
            balanceKES: totalAmount,
            notes: this.buildNotes(dto),
          },
        });

        if (this.prisma.invoiceItem && inv?.id) {
          for (const item of dto.items) {
            await this.prisma.invoiceItem.create({
              data: {
                invoiceId: inv.id,
                description: item.description,
                quantity: item.quantity,
                unitPriceKES: item.unitPriceKES,
                lineTotal: (Number(item.quantity) || 1) * (Number(item.unitPriceKES) || 0),
              },
            });
          }
        }

        return inv;
      }
      throw new Error('Database connection unavailable');
    } catch (err: any) {
      throw new BadRequestException(`Failed to create invoice: ${err.message || 'Database error'}`);
    }
  }

  /**
   * Create one invoice per currently admitted patient using standard programme
   * rates. Calling it again on the same day skips admissions already invoiced,
   * so finance staff can safely use it as a daily/weekly billing run.
   */
  async generateAutomaticInvoices() {
    if (!this.prisma?.admission?.findMany) {
      throw new BadRequestException('Admissions repository is unavailable.');
    }

    const admissions = await this.prisma.admission.findMany({
      where: { isActive: true },
      orderBy: { admissionDate: 'asc' },
    });
    const today = new Date().toDateString();
    const created: any[] = [];
    const skipped: string[] = [];

    for (const admission of admissions ?? []) {
      const admissionNumber =
        this.invoiceValue(admission, 'admissionNumber', 'admission_number') || admission.id;
      const existing = this.prisma.invoice?.findMany
        ? await this.prisma.invoice.findMany({ where: { admissionId: admission.id } })
        : [];
      const alreadyToday = (existing ?? []).some((invoice: any) => {
        const isAuto = /Source:\s*AUTO/i.test(String(invoice.notes ?? ''));
        const issued = this.invoiceValue(invoice, 'issueDate', 'issue_date', 'createdAt', 'created_at');
        return isAuto && (issued ? new Date(issued).toDateString() : today) === today;
      });
      if (alreadyToday) {
        skipped.push(admissionNumber);
        continue;
      }

      const patientId = this.invoiceValue(admission, 'patientId', 'patient_id');
      const patient = patientId && this.prisma.patient?.findUnique
        ? await this.prisma.patient.findUnique({ where: { id: patientId } })
        : null;
      const guardian = patientId && this.prisma.emergencyContact?.findMany
        ? (
            await this.prisma.emergencyContact.findMany({
              where: { patientId, relationship: 'GUARDIAN' },
            })
          )?.[0]
        : null;
      const whatsappNumber =
        this.invoiceValue(guardian, 'alternativePhone', 'alternative_phone') ||
        this.invoiceValue(guardian, 'phone') ||
        undefined;
      const program = String(
        this.invoiceValue(admission, 'programType', 'program_type') ?? 'DETOX_ONLY',
      );
      const rate = PROGRAM_RATES[program] ?? PROGRAM_RATES.DETOX_ONLY;
      const items: CreateInvoiceDto['items'] = [
        {
          description: `${rate.label} (${admissionNumber})`,
          quantity: 1,
          unitPriceKES: rate.amount,
        },
      ];
      if (rate.inpatient) {
        items.push({
          description: 'Accommodation / bed charge (daily)',
          quantity: 1,
          unitPriceKES: BED_RATE_KES,
        });
      }

      const invoice = await this.createInvoice({
        patientId,
        admissionId: admission.id,
        items,
        autoGenerated: true,
        billToName: this.patientName(patient) || undefined,
        billToPhone: this.invoiceValue(guardian, 'phone') || patient?.phone || undefined,
        whatsappNumber: whatsappNumber ? String(whatsappNumber) : undefined,
        notes: `Admission ${admissionNumber}`,
      });
      created.push(invoice);
    }

    return {
      generated: created.length,
      skipped: skipped.length,
      skippedAdmissions: skipped,
      totalKES: created.reduce(
        (sum, invoice) =>
          sum + Number(this.invoiceValue(invoice, 'totalAmountKES', 'total_amount') ?? 0),
        0,
      ),
      invoices: created,
    };
  }

  async recordPayment(dto: RecordPaymentDto) {
    if (!dto.invoiceId || !dto.amountKES || !dto.paymentMethod) {
      throw new BadRequestException('Invoice ID, payment amount, and payment method are required.');
    }

    const recNumber = this.generateReceiptNumber();

    try {
      if (this.prisma && this.prisma.payment) {
        return await this.prisma.$transaction(async (tx) => {
          const invoice = await tx.invoice.findUnique({ where: { id: dto.invoiceId } });
          if (!invoice) {
            throw new NotFoundException(`Invoice ${dto.invoiceId} not found.`);
          }

          const currentPaid = Number(
            this.invoiceValue(invoice, 'paidAmountKES', 'paidAmount', 'paid_amount') ?? 0,
          );
          const total = Number(
            this.invoiceValue(invoice, 'totalAmountKES', 'totalAmount', 'total_amount') ?? 0,
          );
          const newPaid = currentPaid + Number(dto.amountKES);
          const newBalance = Math.max(0, total - newPaid);
          const newStatus =
            newBalance === 0
              ? InvoiceStatus.FULLY_PAID
              : InvoiceStatus.PARTIALLY_PAID;

          await tx.invoice.update({
            where: { id: dto.invoiceId },
            data: {
              paidAmountKES: newPaid,
              balanceKES: newBalance,
              status: newStatus as any,
            },
          });

          return await tx.payment.create({
            data: {
              receiptNumber: recNumber,
              invoiceId: dto.invoiceId,
              amountKES: Number(dto.amountKES),
              paymentMethod: dto.paymentMethod as any,
              transactionRef: dto.transactionRef || null,
              receivedBy: dto.receivedBy || 'Finance Desk',
            },
          });
        });
      }
      throw new Error('Database connection unavailable');
    } catch (err: any) {
      throw new BadRequestException(`Failed to record payment: ${err.message || 'Database error'}`);
    }
  }

  async triggerDarajaStk(dto: TriggerMpesaStkDto) {
    const invoice = await this.getInvoiceOrThrow(dto.invoiceId);
    const balance = Number(
      this.invoiceValue(invoice, 'balanceKES', 'balance_due') ?? 0,
    );
    if (balance <= 0) {
      throw new BadRequestException('This invoice has no outstanding balance.');
    }
    if (Number(dto.amountKES) > balance) {
      throw new BadRequestException(
        `Amount exceeds the invoice balance of KES ${balance.toLocaleString('en-KE')}.`,
      );
    }

    return this.mpesa.initiateStk({
      invoiceId: invoice.id,
      invoiceNumber: this.invoiceNumber(invoice),
      phoneNumber: dto.phoneNumber,
      amountKES: dto.amountKES,
    });
  }

  private async getInvoiceOrThrow(id: string) {
    if (!this.prisma?.invoice?.findUnique) {
      throw new BadRequestException('Invoices repository is unavailable.');
    }
    const invoice = await this.prisma.invoice.findUnique({ where: { id } });
    if (!invoice) throw new NotFoundException(`Invoice ${id} not found.`);
    return invoice;
  }

  private async buildInvoiceDocument(id: string, overrideRecipient?: string) {
    const invoice = await this.getInvoiceOrThrow(id);
    const items = this.prisma.invoiceItem?.findMany
      ? await this.prisma.invoiceItem.findMany({ where: { invoiceId: id } })
      : [];
    const payments = this.prisma.payment?.findMany
      ? await this.prisma.payment.findMany({ where: { invoiceId: id } })
      : [];

    const notes = String(invoice.notes ?? '');
    let patientId = this.invoiceValue(invoice, 'patientId', 'patient_id');
    if (!patientId && invoice.admissionId && this.prisma.admission?.findUnique) {
      const admission = await this.prisma.admission.findUnique({
        where: { id: invoice.admissionId },
      });
      patientId = this.invoiceValue(admission, 'patientId', 'patient_id');
    }
    const patient =
      patientId && this.prisma.patient?.findUnique
        ? await this.prisma.patient.findUnique({ where: { id: patientId } })
        : null;

    const generated = await this.pdf.generate({ invoice, items, payments, patient });
    const recipient =
      overrideRecipient?.trim() ||
      patient?.phone ||
      this.noteValue(notes, 'Phone') ||
      '';
    const number = this.invoiceNumber(invoice);
    const total = Number(this.invoiceValue(invoice, 'totalAmountKES', 'total_amount') ?? 0);

    return {
      invoice,
      ...generated,
      recipient,
      caption: `Calyvia Wellness Center invoice ${number} — KES ${total.toLocaleString('en-KE')}. Please pay promptly.`,
    };
  }

  async generateInvoicePdf(id: string) {
    const { bytes, fileName } = await this.buildInvoiceDocument(id);
    return { bytes, fileName };
  }

  async sendInvoiceViaWhatsApp(id: string, recipient?: string) {
    const doc = await this.buildInvoiceDocument(id, recipient);
    if (!doc.recipient) {
      throw new BadRequestException(
        'No phone number is linked to this invoice. Provide a recipient number to send it.',
      );
    }
    return this.communication.sendWhatsAppDocument({
      recipient: doc.recipient,
      buffer: doc.bytes,
      fileName: doc.fileName,
      caption: doc.caption,
      recipientType: 'PATIENT',
    });
  }

  /**
   * Hard-delete an invoice. Payments reference invoices with ON DELETE RESTRICT,
   * so they are removed first; their M-Pesa rows remain as orphaned audit rows
   * because that foreign key uses ON DELETE SET NULL.
   */
  async deleteInvoice(id: string) {
    if (!this.prisma?.invoice?.delete) {
      throw new BadRequestException('Invoices repository is unavailable.');
    }
    const invoice = await this.getInvoiceOrThrow(id);

    if (this.prisma.payment?.findMany && this.prisma.payment?.delete) {
      const payments = await this.prisma.payment.findMany({ where: { invoiceId: id } });
      for (const payment of payments ?? []) {
        await this.prisma.payment.delete({ where: { id: payment.id } });
      }
    }
    if (this.prisma.invoiceItem?.findMany && this.prisma.invoiceItem?.delete) {
      const items = await this.prisma.invoiceItem.findMany({ where: { invoiceId: id } });
      for (const item of items ?? []) {
        await this.prisma.invoiceItem.delete({ where: { id: item.id } });
      }
    }

    await this.prisma.invoice.delete({ where: { id } });
    return { success: true, id, invoiceNumber: this.invoiceNumber(invoice) };
  }

  async getInvoices(patientId?: string) {
    try {
      if (this.prisma && this.prisma.invoice) {
        const invoices = await this.prisma.invoice.findMany({
          ...(patientId ? { where: { patientId } } : {}),
          orderBy: { issueDate: 'desc' },
        });
        return await Promise.all(
          (invoices ?? []).map(async (invoice: any) => {
            const patientId = this.invoiceValue(invoice, 'patientId', 'patient_id');
            const patient =
              patientId && this.prisma.patient?.findUnique
                ? await this.prisma.patient.findUnique({ where: { id: patientId } })
                : null;
            return {
              ...invoice,
              billToName:
                this.noteValue(invoice.notes, 'Bill to') || this.patientName(patient) || null,
              billToPhone:
                this.noteValue(invoice.notes, 'Phone') || patient?.phone || null,
              source: this.noteValue(invoice.notes, 'Source'),
            };
          }),
        );
      }
    } catch (err) {
      console.warn('Invoices fetch error:', err);
    }
    return [];
  }

  async getPayments() {
    try {
      if (this.prisma && this.prisma.payment) {
        return await this.prisma.payment.findMany({
          orderBy: { paymentDate: 'desc' },
        });
      }
    } catch (err) {
      console.warn('Payments fetch error:', err);
    }
    return [];
  }
}
